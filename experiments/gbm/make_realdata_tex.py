#!/usr/bin/env python3
r"""Emit paper/realdata.tex from experiments/gbm/last_eval.json.

Keeps the real-CTIME numbers in the paper traceable to the run that produced
them, the same way paper/results.tex is emitted by the simulator harness.

For each metric two macros are written:
    \RealAriaAcc     mean only, for prose
    \RealAriaAccPM   mean \pm std across training seeds, for tables

    python3 experiments/gbm/make_realdata_tex.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "experiments" / "gbm" / "last_eval.json"
DST = ROOT / "paper" / "realdata.tex"

METRICS = {
    "ariaAcc": "RealAriaAcc",
    "rangeAcc": "RealRangeAcc",
    "computeIso": "RealComputeIso",
    "sensorIso": "RealSensorIso",
    "novelIso": "RealNovelIso",
    "novelAsCompute": "RealNovelAsCompute",
    "energyCompute": "RealEnergyCompute",
    "energyNovel": "RealEnergyNovel",
}


def pct(x: float) -> str:
    return f"{100.0 * float(x):.1f}"


def main() -> None:
    d = json.loads(SRC.read_text())
    std = d.get("std", {})
    seeds = d.get("seeds", [])
    per_class = min(d["byFamily"].values())

    lines = [
        "% Auto-generated by experiments/gbm/make_realdata_tex.py from",
        "% experiments/gbm/last_eval.json. Do not edit by hand.",
        f"\\newcommand{{\\RealCubes}}{{{d['nCubes']}}}",
        f"\\newcommand{{\\RealPerClass}}{{{per_class}}}",
        f"\\newcommand{{\\RealTrials}}{{{d['nTrials']}}}",
        f"\\newcommand{{\\RealSeeds}}{{{len(seeds) if seeds else 1}}}",
        f"\\newcommand{{\\RealEvalSeed}}{{{d.get('evalSeed', 123)}}}",
    ]
    for key, name in METRICS.items():
        mean = pct(d[key])
        sd = pct(std.get(key, 0.0))
        lines.append(f"\\newcommand{{\\{name}}}{{{mean}}}")
        lines.append(f"\\newcommand{{\\{name}PM}}{{{mean}\\pm{sd}}}")
    lines.append("")

    DST.write_text("\n".join(lines))
    n = len(seeds) if seeds else 1
    print(f"wrote {DST.relative_to(ROOT)} from n={d['nCubes']} run, {n} training seed(s)")


if __name__ == "__main__":
    main()
